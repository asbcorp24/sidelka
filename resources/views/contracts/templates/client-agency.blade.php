<h2>1. Предмет и модель работы</h2>
<ol>
    <li>Заказчик поручает, а Площадка за вознаграждение совершает юридические и фактические действия, связанные с поиском и подбором независимых исполнителей услуг по уходу, согласованием условий заказов, организацией электронного документооборота, приемом денежных средств для последующего расчета с исполнителем и сопровождением заказа.</li>
    <li>Площадка не является медицинской организацией, работодателем сиделки или непосредственным исполнителем услуг по уходу. Договор оказания услуг по конкретному заказу заключается непосредственно между Заказчиком и выбранной сиделкой.</li>
    <li>В части организационных действий Площадка действует от своего имени. В части исполнения поручений, прямо указанных в карточке заказа и индивидуальном договоре, Площадка может действовать от имени Заказчика. Права и обязанности по услугам ухода возникают непосредственно между Заказчиком и сиделкой.</li>
    <li>Заказчик уведомлен и согласен, что Площадка может одновременно действовать как агент сиделки в части поиска заказов, приема оплаты, удержания агентского вознаграждения и перечисления остатка исполнителю.</li>
</ol>

<h2>2. Обязанности Площадки</h2>
<ol>
    <li>Предоставить доступ к каталогу, CRM и средствам оформления заказа.</li>
    <li>Передавать приглашения подходящим сиделкам, организовывать согласование графика, стоимости и состава услуг.</li>
    <li>Формировать электронные документы по сведениям, введенным сторонами, и хранить историю их подписания.</li>
    <li>Принимать оплату по заказам в порядке, предусмотренном карточкой заказа, удерживать средства до наступления условий перечисления и проводить возвраты по правилам заказа.</li>
    <li>Предоставлять сведения о движении денежных средств и статусах заказа в личном кабинете.</li>
</ol>

<h2>3. Обязанности Заказчика</h2>
<ol>
    <li>Предоставлять достоверные контактные, паспортные и иные необходимые сведения.</li>
    <li>До оформления заказа сообщить обо всех существенных особенностях состояния подопечного, рисках, противопоказаниях, наличии инфекционных заболеваний, требуемых навыках и специальных условиях.</li>
    <li>Не поручать сиделке медицинские манипуляции, для которых требуются лицензия, назначение врача или квалификация, если соответствующие документы не подтверждены.</li>
    <li>Своевременно оплачивать заказы и подтвержденные дополнительные расходы.</li>
    <li>Обеспечить законное основание для передачи Площадке и сиделке персональных данных подопечного, в том числе сведений о состоянии здоровья.</li>
</ol>

<h2>4. Расчеты и агентское вознаграждение</h2>
<ol>
    <li>Стоимость услуг сиделки, график и общая сумма определяются в индивидуальном договоре по заказу.</li>
    <li>Заказчик перечисляет деньги Площадке для исполнения поручения и последующего расчета с сиделкой. Поступление денег на счет Площадки не означает, что Площадка стала исполнителем услуг ухода.</li>
    <li>Агентское вознаграждение Площадки обычно удерживается из суммы, причитающейся сиделке, в размере, установленном партнерским договором с сиделкой. Иной порядок может быть прямо указан в заказе.</li>
    <li>История операций в личном кабинете и электронный отчет по заказу являются отчетом Агента. При отсутствии мотивированных возражений в течение 5 календарных дней отчет считается принятым.</li>
</ol>

<h2>5. Ответственность</h2>
<ol>
    <li>Сиделка самостоятельно отвечает перед Заказчиком за качество, безопасность и своевременность принятых на себя услуг.</li>
    <li>Площадка отвечает за надлежащее выполнение собственных организационных и расчетных обязанностей, но не отвечает за действия сторон, скрытые ими обстоятельства и недостоверные сведения.</li>
    <li>Площадка вправе приостановить заказ, выплаты или доступ к сервису при признаках мошенничества, угрозе жизни и здоровью, споре о факте оказания услуг либо требовании государственного органа.</li>
</ol>

<h2>6. Простая электронная подпись</h2>
<ol>
    <li>Стороны признают одноразовый код, направленный на подтвержденный телефон или email, простой электронной подписью владельца соответствующего средства связи.</li>
    <li>Документ считается подписанным после ввода корректного кода на странице Площадки. Система сохраняет хеш документа, дату, IP-адрес, сведения о браузере, канал доставки и протокол проверки кода.</li>
    <li>Заказчик обязан не передавать коды третьим лицам и немедленно уведомить Площадку об утрате контроля над телефоном, email или аккаунтом.</li>
    <li>Изменение текста после подписания требует формирования новой версии документа и повторного подписания.</li>
</ol>

